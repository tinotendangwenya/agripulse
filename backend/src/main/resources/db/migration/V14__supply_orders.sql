CREATE TABLE supply_orders (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  product_id BIGINT NOT NULL,
  supplier_id BIGINT NOT NULL,
  buyer_id BIGINT NOT NULL,
  product_name VARCHAR(150) NOT NULL,
  unit VARCHAR(20) NOT NULL,
  quantity DECIMAL(12,2) NOT NULL,
  unit_price DECIMAL(12,2) NOT NULL,
  currency VARCHAR(3) NOT NULL,
  total_price DECIMAL(14,2) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  delivery_method VARCHAR(20) NOT NULL,
  delivery_address VARCHAR(255),
  payment_method VARCHAR(20) NOT NULL,
  payment_status VARCHAR(20) NOT NULL DEFAULT 'UNPAID',
  note VARCHAR(500),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_sorder_product FOREIGN KEY (product_id) REFERENCES supply_products(id),
  CONSTRAINT fk_sorder_supplier FOREIGN KEY (supplier_id) REFERENCES supplier_profiles(user_id),
  CONSTRAINT fk_sorder_buyer FOREIGN KEY (buyer_id) REFERENCES users(id),
  INDEX idx_sorder_buyer (buyer_id, status),
  INDEX idx_sorder_supplier (supplier_id, status)
);