CREATE TABLE roles (
  id TINYINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(30) NOT NULL UNIQUE
);
INSERT INTO roles (name) VALUES ('FARMER'), ('BUYER'), ('SUPPLIER'), ('EXPERT'), ('ADMIN');

CREATE TABLE users (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  full_name VARCHAR(150) NOT NULL,
  email VARCHAR(255) UNIQUE,
  phone VARCHAR(20) UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role_id TINYINT UNSIGNED NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id),
  CONSTRAINT chk_users_contact CHECK (email IS NOT NULL OR phone IS NOT NULL)
);

CREATE TABLE farms (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  owner_id BIGINT NOT NULL,
  name VARCHAR(150) NOT NULL,
  province VARCHAR(60) NOT NULL,
  district VARCHAR(80),
  latitude DECIMAL(9,6),
  longitude DECIMAL(9,6),
  size_hectares DECIMAL(10,2),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_farms_owner FOREIGN KEY (owner_id) REFERENCES users(id)
);

CREATE TABLE crop_records (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  farm_id BIGINT NOT NULL,
  crop_name VARCHAR(80) NOT NULL,
  variety VARCHAR(80),
  area_hectares DECIMAL(10,2),
  planting_date DATE,
  expected_harvest_date DATE,
  status VARCHAR(30) NOT NULL DEFAULT 'PLANNED',
  notes TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_crops_farm FOREIGN KEY (farm_id) REFERENCES farms(id)
);
